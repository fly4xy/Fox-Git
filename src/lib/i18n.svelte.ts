export function setLanguage(language: Language) {
	const system = navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
	active = language === 'system' ? system : language;
	document.documentElement.lang = active;
}

export const locale = () => (active === 'ru' ? 'ru-RU' : 'en-GB');

export function t(key: Key, params: Record<string, string | number> = {}) {
	return dictionaries[active][key].replace(/\{(\w+)\}/g, (_, name) => String(params[name]));
}
